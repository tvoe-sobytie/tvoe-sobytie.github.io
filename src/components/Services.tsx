// ==================== МОДАЛЬНОЕ ОКНО ====================
function ServiceModal({ service, onClose }: ServiceModalProps) {
    React.useEffect(() => {
        if (service) {
            document.body.style.overflow = 'hidden';
        }
        return () => {
            document.body.style.overflow = 'auto';
        };
    }, [service]);

    if (!service) return null;

    // Функция для форматирования текста с золотыми акцентами
    const formatTextWithGold = (text: string) => {
        // Заменяем маркеры • на золотые звёздочки
        if (text.trim().startsWith('•')) {
            return (
                <div className="flex items-start gap-2">
                    <span className="text-amber-500 text-sm mt-0.5">✦</span>
                    <span className="text-stone-600 text-sm leading-relaxed">{text.trim().substring(1).trim()}</span>
                </div>
            );
        }
        // Заголовки блоков (начинаются с цифры или "БЛОК")
        if (text.match(/^\d+\./) || text.startsWith('БЛОК')) {
            return (
                <div className="relative mt-4 first:mt-0">
                    <div className="absolute left-0 top-0 bottom-0 w-[2px] bg-gradient-to-b from-amber-400 via-amber-500 to-amber-400 rounded-full"></div>
                    <h3 className="font-serif text-lg font-bold text-stone-800 pl-4 tracking-wide">
                        {text}
                    </h3>
                </div>
            );
        }
        // Обычный текст
        return <p className="text-stone-600 text-sm leading-relaxed pl-4">{text}</p>;
    };

    const renderDescription = () => {
        return (
            <div className="space-y-3">
                {service.longDescription.map((paragraph, idx) => (
                    <div key={idx}>
                        {formatTextWithGold(paragraph)}
                    </div>
                ))}
            </div>
        );
    };

    return (
        <div className="fixed inset-0 z-[100] flex items-center justify-center bg-black/50 backdrop-blur-sm overflow-y-auto py-8">
            <div className="relative bg-[#FDF7F0] rounded-3xl max-w-3xl w-full mx-4 max-h-[90vh] overflow-y-auto shadow-2xl">
                {/* Заголовок с золотой линией */}
                <div className="sticky top-0 bg-[#FDF7F0] border-b border-stone-200 px-6 py-4 z-10">
                    <div className="flex justify-between items-center">
                        <div className="flex items-center gap-3">
                            <div className="w-1 h-8 bg-gradient-to-b from-amber-400 to-amber-500 rounded-full"></div>
                            <h2 className="font-serif text-2xl text-stone-800 font-bold tracking-wide">{service.name}</h2>
                        </div>
                        <button onClick={onClose} className="text-stone-400 text-3xl hover:text-amber-500 transition">×</button>
                    </div>
                </div>

                {/* Содержимое с золотыми акцентами */}
                <div className="p-6">
                    {renderDescription()}
                </div>

                {/* Нижняя золотая линия */}
                <div className="px-6 pb-4">
                    <div className="w-full h-[1px] bg-gradient-to-r from-transparent via-amber-400/50 to-transparent"></div>
                </div>
            </div>
        </div>
    );
}

